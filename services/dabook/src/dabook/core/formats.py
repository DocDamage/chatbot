"""
Dataset writers: JSONL (always), Parquet and the Hugging Face ``datasets`` directory layout.

Parquet and HF need ``pyarrow`` (``pip install dabook[export]``). The HF layout is a directory with
a ``README.md`` dataset card (YAML ``configs`` front matter) and ``data/<split>-*.parquet`` files,
loadable with ``datasets.load_dataset("<dir>")``.
"""

from __future__ import annotations

import json
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from dabook.core.atomic import write_file

HF_SPLIT_NAMES = {"train": "train", "val": "validation", "test": "test"}


def write_jsonl(path: Path, records: Sequence[dict[str, Any]]) -> None:
    payload = "".join(json.dumps(r, ensure_ascii=False) + "\n" for r in records)
    write_file(path, payload.encode("utf-8"))


def read_jsonl(path: Path) -> list[dict[str, Any]]:
    if not path.is_file():
        return []
    return [json.loads(line) for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]


def _require_pyarrow() -> Any:
    try:
        import pyarrow  # noqa: F401
        import pyarrow.parquet  # noqa: F401
    except ImportError:
        raise RuntimeError(
            "Parquet/HF export needs pyarrow: install it with `pip install dabook[export]`"
        ) from None
    import pyarrow as pa

    return pa


def _table(pa: Any, records: Sequence[dict[str, Any]]) -> Any:
    try:
        return pa.Table.from_pylist(list(records))
    except (pa.ArrowInvalid, pa.ArrowTypeError):
        # Heterogeneous nested values cannot share one Arrow schema: keep them as JSON strings.
        flat = [
            {k: (json.dumps(v, ensure_ascii=False) if isinstance(v, (dict, list)) else v) for k, v in r.items()}
            for r in records
        ]
        return pa.Table.from_pylist(flat)


def write_parquet(path: Path, records: Sequence[dict[str, Any]]) -> bool:
    """Write *records* as one Parquet file. Returns False (nothing written) for no records."""
    if not records:
        return False
    pa = _require_pyarrow()
    import pyarrow.parquet as pq

    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(f".{path.name}.tmp")
    pq.write_table(_table(pa, records), tmp, compression="zstd")
    tmp.replace(path)
    return True


def read_parquet(path: Path) -> list[dict[str, Any]]:
    _require_pyarrow()
    import pyarrow.parquet as pq

    return pq.read_table(path).to_pylist()


def render_dataset_card(name: str, splits: dict[str, int], notes: dict[str, Any]) -> str:
    """README.md for a Hugging Face dataset directory."""
    configs = "".join(
        f"  - split: {HF_SPLIT_NAMES[s]}\n    path: data/{HF_SPLIT_NAMES[s]}-*.parquet\n"
        for s, n in splits.items()
        if n
    )
    lines = [
        "---",
        "configs:",
        "- config_name: default",
        "  data_files:",
        configs.rstrip("\n"),
        "---",
        "",
        f"# {name}",
        "",
        "Generated by DABOOK from the books listed below. Every record carries provenance "
        "(`book_sha256`, `license_status`, `source_node_ids`, `pages`, `generator`, `dabook_version`).",
        "",
        "## Splits",
        "",
        *[f"- **{HF_SPLIT_NAMES[s]}**: {n} records" for s, n in splits.items()],
        "",
        "Splits are made by chapter: no chapter appears in more than one split.",
        "",
    ]
    if notes.get("books"):
        lines += ["## Books", ""]
        for b in notes["books"]:
            lines.append(
                f"- {b.get('title') or b.get('sha256', '')[:12]} "
                f"(license: {b.get('license_status')}, quality: {b.get('quality_score')})"
            )
        lines.append("")
    if notes.get("generators"):
        lines += ["## Generators", "", *[f"- {g}: {n}" for g, n in notes["generators"].items()], ""]
    if notes.get("dedup"):
        lines += ["## Deduplication", "", f"`{json.dumps(notes['dedup'])}`", ""]
    return "\n".join(lines) + "\n"


def write_hf_layout(
    directory: Path, name: str, splits: dict[str, Sequence[dict[str, Any]]], notes: dict[str, Any]
) -> dict[str, int]:
    """Write ``directory/README.md`` and ``directory/data/<split>-00000-of-00001.parquet``."""
    counts = {s: len(rows) for s, rows in splits.items()}
    for split, rows in splits.items():
        hf = HF_SPLIT_NAMES[split]
        write_parquet(directory / "data" / f"{hf}-00000-of-00001.parquet", rows)
    write_file(directory / "README.md", render_dataset_card(name, counts, notes).encode("utf-8"))
    return counts
