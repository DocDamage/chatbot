/**
 * Source Code Retrieval Benchmark & Phase 14 Exit Gate Suite (CRK Phase 14)
 */

import { SourceCodePack } from '../SourceCodePack';
import { RepoQualitySignals } from '../../../types/source-code-pack';

describe('Source Code Retrieval Benchmark & Phase 14 Exit Gate', () => {
  let pack: SourceCodePack;
  const goodSignals: RepoQualitySignals = {
    declaredLicense: 'MIT',
    hasReadme: true,
    hasTests: true,
    isFork: false,
    stars: 350,
  };

  beforeEach(() => {
    pack = new SourceCodePack();
  });

  it('Exit Gate Criterion 1: Structural code indexing extracts symbols, lines, and relationships', () => {
    const code = `
import { Observable } from 'rxjs';
export interface EventPayload {
  eventId: string;
}

export class EventDispatcher {
  private listenerCount = 0;

  public dispatch(payload: EventPayload): boolean {
    return payload.eventId.length > 0;
  }
}
`;

    const chunks = pack.indexFile({
      repository: 'microsoft/sample-event-hub',
      commit: '7b8f9a2',
      path: 'src/dispatcher.ts',
      content: code,
      repoSignals: goodSignals,
    });

    expect(chunks.length).toBeGreaterThanOrEqual(2);
    const classChunk = chunks.find((c) => c.symbol?.name === 'EventDispatcher');
    expect(classChunk).toBeDefined();
    expect(classChunk?.symbol?.type).toBe('class');
    expect(classChunk?.relationships.imports).toContain("import { Observable } from 'rxjs';");
    expect(classChunk?.provenance.startLine).toBeGreaterThan(0);
    expect(classChunk?.provenance.sourceUrl).toContain('microsoft/sample-event-hub');
  });

  it('Exit Gate Criterion 2: Generated, vendor, lock, minified, and duplicate content is controlled', () => {
    // 1. Lock file rejected
    const lockChunks = pack.indexFile({
      repository: 'test/repo',
      commit: '1111111',
      path: 'package-lock.json',
      content: '{"name": "test", "lockfileVersion": 3}',
      repoSignals: goodSignals,
    });
    expect(lockChunks.length).toBe(0);

    // 2. Generated code header rejected
    const generatedCode = '// @generated by protoc-gen-ts. DO NOT EDIT.\nexport class UserProto {}';
    const genChunks = pack.indexFile({
      repository: 'test/repo',
      commit: '1111111',
      path: 'src/user.proto.ts',
      content: generatedCode,
      repoSignals: goodSignals,
    });
    expect(genChunks.length).toBe(0);

    // 3. Duplicate fork repo rejected
    const forkSignals: RepoQualitySignals = {
      ...goodSignals,
      isFork: true,
    };
    const forkChunks = pack.indexFile({
      repository: 'forker/sample-event-hub',
      commit: '2222222',
      path: 'src/main.ts',
      content: 'export function main() {}',
      repoSignals: forkSignals,
    });
    expect(forkChunks.length).toBe(0);

    // 4. Near-duplicate code indexed only once
    const originalCode = 'export function add(a: number, b: number): number { return a + b; }';
    const nearDuplicateCode = 'export function add(a: number, b: number): number {\n  // comment\n  return a + b;\n}';

    const firstChunks = pack.indexFile({
      repository: 'test/repo',
      commit: '1111111',
      path: 'src/math.ts',
      content: originalCode,
      repoSignals: goodSignals,
    });
    expect(firstChunks.length).toBe(1);

    const secondChunks = pack.indexFile({
      repository: 'test/repo',
      commit: '1111111',
      path: 'src/math-copy.ts',
      content: nearDuplicateCode,
      repoSignals: goodSignals,
    });
    expect(secondChunks.length).toBe(0); // Near duplicate skipped
  });

  it('Exit Gate Criterion 3: Provenance is complete to locate original repository, commit, and file path', () => {
    const pythonCode = `
def parse_markdown_headers(text: str) -> list[str]:
    """Extracts all markdown headers from text."""
    return [line for line in text.splitlines() if line.startswith('#')]
`;

    const chunks = pack.indexFile({
      repository: 'python-community/doc-tools',
      commit: '3e4a5b6c',
      path: 'doc_tools/parser.py',
      content: pythonCode,
      repoSignals: goodSignals,
    });

    expect(chunks.length).toBe(1);
    const chunk = chunks[0];
    expect(chunk.provenance.repository).toBe('python-community/doc-tools');
    expect(chunk.provenance.commit).toBe('3e4a5b6c');
    expect(chunk.provenance.path).toBe('doc_tools/parser.py');
    expect(chunk.provenance.repoLicense).toBe('MIT');
    expect(chunk.provenance.sourceUrl).toBe(
      'https://github.com/python-community/doc-tools/blob/3e4a5b6c/doc_tools/parser.py'
    );
  });

  it('Exit Gate Criterion 4: Coding benchmark query retrieves exact symbol and idiomatic pattern', () => {
    pack.indexFile({
      repository: 'rust-lang/example-server',
      commit: 'fa4109b',
      path: 'src/handler.rs',
      content: `
pub fn handle_connection(stream: &mut TcpStream) -> Result<(), Error> {
    let mut buffer = [0; 1024];
    stream.read(&mut buffer)?;
    Ok(())
}
`,
      repoSignals: goodSignals,
    });

    const results = pack.search('handle_connection TcpStream');
    expect(results.length).toBeGreaterThan(0);
    expect(results[0].symbol?.name).toBe('handle_connection');
    expect(results[0].language).toBe('rust');
  });

  it('Exit Gate Criterion 5: No execution occurs merely because code was retrieved (§2672)', () => {
    const maliciousPayload = `
export function exploit() {
  process.exit(1);
}
`;
    const chunks = pack.indexFile({
      repository: 'adversary/poc',
      commit: 'bad1234',
      path: 'src/payload.ts',
      content: maliciousPayload,
      repoSignals: goodSignals,
    });

    expect(chunks.length).toBe(1);
    const retrieved = pack.search('exploit');
    expect(retrieved.length).toBe(1);

    // Verify it is purely data representation without invocation or side-effect
    expect(typeof retrieved[0].content).toBe('string');
    expect(retrieved[0].symbol?.name).toBe('exploit');
  });
});
